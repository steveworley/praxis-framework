// Generate src/template-data.generated.ts: the repo-root `template/` tree
// embedded as data (each file as { path, base64, mode }).
//
// Why embed instead of shipping a `template/` directory: the dashboard bundles
// @praxis-framework/seed into its server build, which severs `import.meta.url`
// from the package's files on disk — so any path-based lookup of a template
// directory fails at runtime. Baking the bytes into the compiled JS makes the
// seed package fully self-contained and deterministic: it works the same
// whether it's run un-bundled (CLI / npx), bundled (dashboard), vendored, or
// symlinked, and the scaffolding is versioned with the package.
//
// Runs via the `prebuild` / `pretest` / `precheck` npm hooks so the generated
// module always exists before tsc / vitest. The output is gitignored — the
// source of truth is the repo-root `template/`.

import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = join(here, '..', '..', '..', 'template');
const dest = join(here, '..', 'src', 'template-data.generated.ts');

function walk(dir) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const abs = join(dir, entry.name);
    if (entry.isDirectory()) {
      out.push(...walk(abs));
    } else if (entry.isFile()) {
      out.push(abs);
    }
  }
  return out;
}

const files = walk(source)
  .map((abs) => {
    const rel = relative(source, abs).split(sep).join('/'); // posix paths
    const mode = statSync(abs).mode & 0o777;
    const base64 = readFileSync(abs).toString('base64');
    return { path: rel, base64, mode };
  })
  .sort((a, b) => a.path.localeCompare(b.path));

if (files.length === 0) {
  console.error(`embed-template: no files found under ${source}`);
  process.exit(1);
}

const body = `// AUTO-GENERATED by scripts/embed-template.mjs — do not edit by hand.
// Source of truth: the repo-root template/ directory. Regenerated on every
// build/test/check via npm pre-hooks.

export interface EmbeddedTemplateFile {
  /** Role-relative posix path, e.g. "lib/tools.yaml". */
  path: string;
  /** File contents, base64-encoded (exact bytes). */
  base64: string;
  /** Unix file mode (permission bits), e.g. 0o644. */
  mode: number;
}

export const EMBEDDED_TEMPLATE: readonly EmbeddedTemplateFile[] = ${JSON.stringify(files, null, 2)};
`;

writeFileSync(dest, body, 'utf-8');
console.log(`embed-template: wrote ${files.length} files → ${relative(join(here, '..'), dest)}`);
